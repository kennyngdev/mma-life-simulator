export const translationCatalogs: Record<Locale, Record<string, string>> = { 'zh-Hant': zhHant, en: { ...en, ...authoredPayloadEn, ...presentationEnglishMessages } }
const cache = createIntlCache()

function validLocale(value: string | null | undefined): value is Locale {
  return value === 'zh-Hant' || value === 'en'
}

export function resolveInitialLocale(
  locationSearch = window.location.search,
  browserLanguages = navigator.languages.length ? navigator.languages : [navigator.language],
): Locale {
  const queryLocale = new URLSearchParams(locationSearch).get('lang')
  if (validLocale(queryLocale)) return queryLocale
  const stored = localStorage.getItem(LOCALE_STORAGE_KEY)
  if (validLocale(stored)) return stored
  const detectedLanguages = browserLanguages.map((language) => language.trim().toLowerCase()).filter(Boolean)
  if (detectedLanguages.some((language) => language === 'zh' || language.startsWith('zh-'))) return 'zh-Hant'
  return detectedLanguages.length ? 'en' : 'zh-Hant'
}

type I18nContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  intl: IntlShape
  t: (id: TranslationKey, values?: Record<string, string | number>) => string
  message: (reference: MessageReference | undefined, fallback?: string) => string
}

const fallbackIntl = createIntl({ locale: 'zh-Hant', messages: zhHant }, cache)
const I18nContext = createContext<I18nContextValue>({
  locale: 'zh-Hant', setLocale: () => undefined, intl: fallbackIntl,
  t: (id, values) => fallbackIntl.formatMessage({ id, defaultMessage: zhHant[id] }, values),
  message: (reference, fallback = '') => reference?.fallback ?? fallback,
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => resolveInitialLocale())
  const intl = useMemo(() => createIntl({ locale, messages: translationCatalogs[locale] }, cache), [locale])
  const setLocale = useCallback((next: Locale) => {
    localStorage.setItem(LOCALE_STORAGE_KEY, next)
    const url = new URL(window.location.href)
    url.searchParams.set('lang', next)
    window.history.replaceState(window.history.state, '', url)
    setLocaleState(next)
  }, [])
  const t = useCallback((id: TranslationKey, values?: Record<string, string | number>) => intl.formatMessage({ id, defaultMessage: zhHant[id] }, values), [intl])
  const message = useCallback((reference: MessageReference | undefined, fallback = '') => {
    const storedFallback = reference?.fallback ?? fallback
    if (locale === 'zh-Hant' || !reference?.messageId) return storedFallback
    const catalog = translationCatalogs[locale] as Record<string, string>
    if (!Object.prototype.hasOwnProperty.call(catalog, reference.messageId)) return storedFallback
    return intl.formatMessage({ id: reference.messageId, defaultMessage: storedFallback }, reference.values)
  }, [intl, locale])

  useEffect(() => {
    document.documentElement.lang = locale
    document.title = t('app.title')
    document.querySelector<HTMLMetaElement>('meta[name="description"]')?.setAttribute('content', t('app.description'))
    document.querySelector<HTMLLinkElement>('link[rel="manifest"]')?.setAttribute('href', `/manifest.${locale}.webmanifest`)
  }, [locale, t])

  const value = useMemo(() => ({ locale, setLocale, intl, t, message }), [locale, setLocale, intl, t, message])
  return createElement(I18nContext.Provider, { value }, createElement(IntlProvider, { locale, messages: translationCatalogs[locale] }, children))
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext)
}
